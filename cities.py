def distance_km(city_a: str, city_b: str) -> float:
    if city_a == city_b:
        return 0.0
    a = CITIES.get(city_a)
    b = CITIES.get(city_b)
    if not a or not b:
        return 999999.0
    lat1, lon1 = map(math.radians, a)
    lat2, lon2 = map(math.radians, b)
    dlat = lat2 - lat1
    dlon = lon2 - lon1
    h = (math.sin(dlat / 2) ** 2
         + math.cos(lat1) * math.cos(lat2) * math.sin(dlon / 2) ** 2)
    return 2 * 6371 * math.asin(math.sqrt(h))


def closest_known_city(name: str) -> str:
    return name if name in CITIES else name
